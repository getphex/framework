<?php

declare(strict_types=1);

namespace Phex\Build\Emitter;

use Phex\Build\Analysis\Analyzer;
use Phex\Build\Analysis\InvalidContainer;
use Phex\Build\Graph\Graph;
use Phex\Build\Graph\Node;
use Phex\Container\Definition\Lifetime;
use Phex\Container\Lifetime\ApplicationScope;
use Phex\Contracts\Routing\EndpointResolver;
use Phex\Contracts\Routing\Matcher;
use Phex\Http\Message\Request;
use Phex\Kernel\Scope\RequestScope;

/** @internal Emit fixed classes for a fully validated dependency graph. */
final class ContainerEmitter
{
    /** @var array<string, int> */
    private array $ids = [];

    /** @var array<string, true> */
    private array $applicationNodes = [];

    public function emit(Graph $graph, string $className): string
    {
        if (preg_match('/^[a-zA-Z_][a-zA-Z0-9_]*(?:\\\\[a-zA-Z_][a-zA-Z0-9_]*)+$/D', $className) !== 1) {
            throw new InvalidContainer('The generated class must have a valid namespace: '.$className);
        }
        $parts = explode('\\', $className);
        $short = array_pop($parts);
        $namespace = implode('\\', $parts);
        $this->ids = [];
        $this->applicationNodes = [];
        foreach (array_keys($graph->nodes) as $index => $type) {
            $this->ids[$type] = $index;
        }
        foreach ($graph->nodes as $node) {
            if ($node->lifetime === Lifetime::Application) {
                $this->applicationNode($node->type, $graph);
            }
        }

        $eager = $graph->definition->routes !== [] || $this->applicationNodes !== [];
        $hasHandler = $graph->definition->handler !== null || $graph->definition->routes !== [];
        $source = "<?php\n\ndeclare(strict_types=1);\n\nnamespace ".$namespace.";\n\n// Generated by phex build. Regenerate from the service definitions.\n";
        $source .= 'final class '.$short.' implements \\Phex\\Contracts\\Kernel\\ScopeResource';
        $source .= $hasHandler ? ', \\Phex\\Contracts\\Container\\ApplicationContainer' : '';
        $source .= "\n{\n    private readonly \\Phex\\Container\\Lifetime\\ApplicationScope \$resources;\n";
        if ($graph->definition->routes !== []) {
            $source .= "    private readonly \\Phex\\Contracts\\Routing\\Matcher \$routes;\n";
        }
        foreach ($graph->nodes as $type => $node) {
            if ($node->lifetime === Lifetime::Application) {
                $source .= '    private ?\\'.$type.' $value'.$this->ids[$type]." = null;\n";
            }
        }
        $source .= "\n    public function __construct()\n    {\n        \$this->resources = new \\Phex\\Container\\Lifetime\\ApplicationScope();\n";
        if ($eager) {
            $source .= "        try {\n";
        }
        if ($graph->definition->routes !== []) {
            $source .= "            \$this->routes = new \\".$className."Matcher();\n";
        }
        foreach ($graph->nodes as $type => $node) {
            if ($node->lifetime === Lifetime::Application) {
                $source .= '            $this->service'.$this->ids[$type]."();\n";
            }
        }
        if ($eager) {
            $source .= "        } catch (\\Throwable \$failure) {\n            \$this->resources->close(\$failure);\n            throw \$failure;\n        }\n";
        }
        $source .= "    }\n";
        $source .= "\n    public function close(): void\n    {\n        \$this->resources->close();\n    }\n\n    /** @internal */\n    public function ownership(): \\Phex\\Container\\Lifetime\\ApplicationScope\n    {\n        return \$this->resources;\n    }\n\n    /** @internal */\n    public function assertOpen(): void\n    {\n        if (\$this->resources->isClosed()) {\n            throw new \\LogicException('The application container is closed.');\n        }\n    }\n";
        if ($graph->definition->routes !== []) {
            $source .= "\n    /** @internal */\n    public function matcher(): \\Phex\\Contracts\\Routing\\Matcher\n    {\n        \$this->assertOpen();\n        return \$this->routes;\n    }\n";
        }
        $source .= "\n    public function request(\\Phex\\Kernel\\Scope\\RequestScope \$scope): \\".$className."Request\n    {\n        \$this->assertOpen();\n        \$context = \$scope->context(\$this);\n        if (\$context instanceof \\".$className."Request) {\n            return \$context;\n        }\n        \$created = new \\".$className."Request(\$this, \$scope);\n        \$scope->bindContext(\$this, \$created);\n        return \$created;\n    }\n";
        if ($hasHandler) {
            $source .= "\n    public function create(\\Phex\\Kernel\\Scope\\RequestScope \$scope): \\Phex\\Contracts\\Http\\Handler\n    {\n        return \$this->request(\$scope)->handler();\n    }\n";
        }
        foreach ($graph->nodes as $type => $node) {
            if (isset($this->applicationNodes[$type])) {
                $source .= $this->getter($node, false);
            }
        }
        $source .= $this->entries($graph, false).$this->registration($graph, false)."}\n\n";
        $source .= 'final class '.$short."Request implements \\Phex\\Contracts\\Kernel\\ScopeResource, \\Phex\\Contracts\\Routing\\EndpointResolver\n{\n    private bool \$closed = false;\n";
        foreach ($graph->nodes as $type => $node) {
            if ($node->lifetime === Lifetime::Request) {
                $source .= '    private ?\\'.$type.' $value'.$this->ids[$type]." = null;\n";
                $source .= '    private bool $building'.$this->ids[$type]." = false;\n";
            }
        }
        $source .= "\n    public function __construct(private readonly \\".$className." \$application, private readonly \\Phex\\Kernel\\Scope\\RequestScope \$scope) {}\n\n    public function close(): void\n    {\n        \$this->closed = true;\n    }\n\n    private function assertOpen(): void\n    {\n        \$this->application->assertOpen();\n        if (\$this->closed || \$this->scope->isClosed()) {\n            throw new \\LogicException('The request container is closed.');\n        }\n    }\n";
        foreach ($graph->nodes as $node) {
            $source .= $this->getter($node, true);
        }
        $source .= $this->entries($graph, true).$this->registration($graph, true);
        $source .= "\n    public function resolve(\\Phex\\Contracts\\Routing\\Endpoint \$endpoint): \\Phex\\Contracts\\Routing\\Endpoint\n    {\n        \$this->assertOpen();\n        \$reference = self::reference(\$endpoint);\n        if (\$reference === null) {\n            return \$endpoint;\n        }\n";
        $endpoints = [];
        foreach ($graph->definition->routes as $route) {
            $endpoints[Analyzer::className($route->endpoint)] = true;
        }
        ksort($endpoints, SORT_STRING);
        foreach (array_keys($endpoints) as $endpoint) {
            $source .= '        if ($reference->type === \\'.$endpoint."::class) {\n            return \$this->service".$this->ids[$endpoint]."();\n        }\n";
        }
        $source .= "        throw new \\LogicException('Unknown compiled endpoint.');\n    }\n\n    private static function reference(mixed \$value): ?\\Phex\\Container\\Routing\\EndpointReference\n    {\n        if (\$value instanceof \\Phex\\Container\\Routing\\EndpointReference) {\n            return \$value;\n        }\n        return null;\n    }\n";
        if ($hasHandler) {
            $expression = $graph->definition->handler !== null
                ? '$this->service'.$this->ids[Analyzer::className($graph->definition->handler)].'()'
                : 'new \\Phex\\Routing\\Router($this->application->matcher(), $this)';
            $source .= "\n    /** @internal */\n    public function handler(): \\Phex\\Contracts\\Http\\Handler\n    {\n        \$this->assertOpen();\n        return ".$expression.";\n    }\n";
        }
        $source .= "}\n";
        $source .= (new MatcherEmitter())->emit($graph->routes, $short.'Matcher');
        // Syntax-check only. The build process never evaluates emitted code.
        if (token_get_all($source, TOKEN_PARSE) === []) {
            throw new InvalidContainer('The generated artifact is empty.');
        }

        return $source;
    }

    private function getter(Node $node, bool $request): string
    {
        $id = $this->ids[$node->type];
        $start = "\n    /** @internal */\n    public function service".$id.'(): \\'.$node->type."\n    {\n        \$this->assertOpen();\n";
        if ($request && $node->lifetime === Lifetime::Application) {
            return $start.'        return $this->application->service'.$id."();\n    }\n";
        }
        $cached = $node->lifetime !== Lifetime::Transient;
        if ($cached) {
            $start .= '        $cached = $this->value'.$id.";\n        if (\$cached !== null) {\n            return \$cached;\n        }\n";
        }
        if ($request && $cached) {
            $start .= '        if ($this->building'.$id.") {\n            throw new \\LogicException('Service construction is already in progress.');\n        }\n";
            $start .= '        $this->building'.$id." = true;\n        try {\n";
        }
        $arguments = [];
        foreach ($node->arguments as $argument) {
            $type = $argument->service;
            $arguments[] = $type === null ? Literal::emit($argument->default) : $this->dependency($type, $request);
        }
        $call = $node->method === null ? 'new \\'.$node->provider : '\\'.$node->provider.'::'.$node->method;
        $construction = '        $value = '.$call.'('.implode(', ', $arguments).");\n";
        $owner = $request ? '$this->scope' : '$this->resources';
        if ($node->resource) {
            $construction .= '        '.$owner."->own(\$value);\n";
        } elseif ($node->possibleResource) {
            $construction .= "        \$this->registerResource(\$value);\n";
        }
        if ($cached) {
            $construction .= '        $this->value'.$id." = \$value;\n";
        }
        $construction .= "        return \$value;\n";
        if ($request && $cached) {
            $start .= preg_replace('/^/m', '    ', rtrim($construction))."\n        } finally {\n            \$this->building".$id." = false;\n        }\n";
        } else {
            $start .= $construction;
        }

        return $start."    }\n";
    }

    private function dependency(string $type, bool $request): string
    {
        return match ($type) {
            ApplicationScope::class => $request ? '$this->application->ownership()' : '$this->resources',
            Matcher::class => $request ? '$this->application->matcher()' : '$this->matcher()',
            Request::class => '$this->scope->request',
            RequestScope::class => '$this->scope',
            EndpointResolver::class => '$this',
            default => '$this->service'.$this->ids[$type].'()',
        };
    }

    private function entries(Graph $graph, bool $request): string
    {
        $source = '';
        $entries = $graph->definition->entries;
        ksort($entries, SORT_STRING);
        foreach ($entries as $name => $type) {
            $type = Analyzer::className($type);
            if ($request || $graph->nodes[$type]->lifetime === Lifetime::Application) {
                $source .= "\n    public function ".$name.'(): \\'.$type."\n    {\n        return \$this->service".$this->ids[$type]."();\n    }\n";
            }
        }

        return $source;
    }

    private function registration(Graph $graph, bool $request): string
    {
        $needed = false;
        foreach ($graph->nodes as $type => $node) {
            if ($node->possibleResource && ($request ? $node->lifetime !== Lifetime::Application : isset($this->applicationNodes[$type]))) {
                $needed = true;
            }
        }
        if (!$needed) {
            return '';
        }

        $owner = $request ? '$this->scope' : '$this->resources';

        return "\n    private function registerResource(mixed \$value): void\n    {\n        if (\$value instanceof \\Phex\\Contracts\\Kernel\\ScopeResource) {\n            ".$owner."->own(\$value);\n        }\n    }\n";
    }

    private function applicationNode(string $type, Graph $graph): void
    {
        if (!isset($graph->nodes[$type]) || isset($this->applicationNodes[$type])) {
            return;
        }
        $this->applicationNodes[$type] = true;
        foreach ($graph->nodes[$type]->arguments as $argument) {
            if ($argument->service !== null) {
                $this->applicationNode($argument->service, $graph);
            }
        }
    }
}
